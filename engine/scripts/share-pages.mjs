// Link previews for section links (climb.html#when-to-swap).
// Link-preview crawlers drop the #fragment, so every section link previews as
// the whole page. For each data-nav section of the static pages this
// writes a tiny same-directory page (climb-when-to-swap.html) carrying that
// section's own title/description and redirecting to climb.html#when-to-swap,
// and lists the covered ids in the page's <meta name="section-share"> so
// section-nav.js puts the shareable address in the bar while you read.
// Zero-API. Rerun after editing a section heading or lede; --check fails on drift.
import { readFileSync, writeFileSync, existsSync, readdirSync, unlinkSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dir = path.join(root, 'ui/v6');
const SITE = 'https://kendubu1.github.io/pred-counter-scout/ui/v6/';
const PAGES = ['climb.html', 'about.html', 'changes.html'];
const check = process.argv.includes('--check');

// same rule as section-nav.js
const slug = (t) => String(t).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'section';
const entities = { amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'", nbsp: ' ', rsquo: '’', lsquo: '‘', mdash: '—', ndash: '–', hellip: '…' };
const text = (html) => html.replace(/<[^>]+>/g, '').replace(/&(#?\w+);/g, (m, e) => entities[e] ?? m).replace(/\s+/g, ' ').trim();
const attr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const clip = (s, n) => (s.length <= n ? s : s.slice(0, s.lastIndexOf(' ', n - 1)).replace(/[,;:—–-]+$/, '') + '…');

const drift = [];
const write = (file, body) => {
  const prev = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (prev === body) return;
  if (check) drift.push(path.relative(root, file));
  else writeFileSync(file, body);
};

for (const page of PAGES) {
  const base = page.replace(/\.html$/, '');
  let src = readFileSync(path.join(dir, page), 'utf8');
  const pageTitle = text(src.match(/<title>([\s\S]*?)<\/title>/)[1]);
  const pageDesc = src.match(/<meta name="description" content="([^"]*)"/)?.[1] ?? '';
  const site = pageTitle.split(' — ')[0];
  const used = new Set(), ids = [], want = new Set();
  for (const m of src.matchAll(/<section\b([^>]*)\bdata-nav="([^"]+)"[^>]*>([\s\S]*?)<\/section>/g)) {
    const [, , label, body] = m;
    let id = (m[0].match(/^<section\b[^>]*\bid="([^"]+)"/) || [])[1];
    if (!id) { const b = slug(text(label)); id = b; let n = 2; while (used.has(id)) id = `${b}-${n++}`; }
    used.add(id); ids.push(id);
    const h2 = body.match(/<h2>([\s\S]*?)<\/h2>/);
    // a trailing tag (MEASURED · 1.17.2) is dropped; a change-notes date leads the title
    const date = h2 && h2[1].match(/<span class="entry-date">([^<]*)<\/span>/);
    const bare = h2 ? text(h2[1].replace(/\s*<span class="(?:tag|entry-date)">[^<]*<\/span>\s*$/, '')).replace(/^\d+\s*·\s*/, '') : text(label);
    const heading = date ? `${text(date[1])}: ${bare}` : bare;
    // the section's first paragraph, else its first bullets (change notes), minus the New/Fix badges
    const lead = body.match(/<p\b[^>]*>([\s\S]*?)<\/p>/)?.[1]
      ?? [...body.matchAll(/<li>([\s\S]*?)<\/li>/g)].slice(0, 3).map((li) => text(li[1].replace(/<span class="k [^"]*">[^<]*<\/span>/g, ''))).join(' · ')
      ?? '';
    const desc = clip(text(lead || pageDesc), 200);
    const title = `${heading} · ${site} · Pred Scout`;
    const stub = `${base}-${id}.html`;
    const target = `${page}#${id}`;
    want.add(stub);
    write(path.join(dir, stub), `<!doctype html>
<!-- generated by engine/scripts/share-pages.mjs from ${page}; do not edit -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${attr(title)}</title>
<meta name="description" content="${attr(desc)}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="Pred Scout">
<meta property="og:title" content="${attr(title)}">
<meta property="og:description" content="${attr(desc)}">
<meta property="og:url" content="${SITE}${stub}">
<meta name="twitter:card" content="summary">
<meta name="robots" content="noindex">
<link rel="canonical" href="${SITE}${target}">
<meta http-equiv="refresh" content="0;url=${target}">
<script>location.replace(${JSON.stringify(target)});</script>
<style>body{background:#0a0a0f;color:#e8e8f0;font:15px/1.55 -apple-system,"Segoe UI",Roboto,sans-serif;padding:2rem 1rem}a{color:#4dabf7}</style>
</head>
<body><a href="${target}">${attr(heading)}</a></body>
</html>
`);
  }
  // drop stubs for sections that no longer exist
  for (const f of readdirSync(dir)) {
    if (f.startsWith(`${base}-`) && f.endsWith('.html') && !want.has(f) && readFileSync(path.join(dir, f), 'utf8').includes('generated by engine/scripts/share-pages.mjs')) {
      if (check) drift.push(`ui/v6/${f} (stale)`); else unlinkSync(path.join(dir, f));
    }
  }
  const block = `<!-- share:begin (engine/scripts/share-pages.mjs) -->
<meta property="og:type" content="article">
<meta property="og:site_name" content="Pred Scout">
<meta property="og:title" content="${attr(pageTitle)}">
<meta property="og:description" content="${pageDesc}">
<meta property="og:url" content="${SITE}${page}">
<meta name="section-share" content="${ids.join(' ')}">
<!-- share:end -->`;
  const re = /<!-- share:begin[\s\S]*?<!-- share:end -->/;
  src = re.test(src) ? src.replace(re, block) : src.replace(/(<meta name="description"[^>]*>\n)/, `$1${block}\n`);
  write(path.join(dir, page), src);
}

if (check && drift.length) {
  console.error(`share pages out of date (run: node engine/scripts/share-pages.mjs):\n  ${drift.join('\n  ')}`);
  process.exit(1);
}
console.log(check ? 'share pages up to date' : 'share pages written');
